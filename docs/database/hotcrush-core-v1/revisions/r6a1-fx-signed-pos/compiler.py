def _replace_contract_identifiers(value: object) -> object:
    """Apply only the two approved physical object renames to nested metadata."""

    replacements = (
        ("scm_supplier_price_observation", "scm_material_price_observation"),
        ("cost_card_material_price", "cost_card_material_cost_selection"),
        ("supplier_price_observation_id", "material_price_observation_id"),
        ("material_price_id", "material_cost_selection_id"),
    )
    if type(value) is str:
        result = value
        for source, target in replacements:
            result = result.replace(source, target)
        return result
    if type(value) is list:
        return [_replace_contract_identifiers(item) for item in value]
    if type(value) is dict:
        return {
            str(_replace_contract_identifiers(key)): _replace_contract_identifiers(item)
            for key, item in value.items()
        }
    return value


