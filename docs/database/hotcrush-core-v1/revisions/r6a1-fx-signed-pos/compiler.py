def _read_relative_regular_file(root_descriptor: int, relative_path: str) -> bytes:
    parsed = PurePosixPath(relative_path)
    if (
        parsed.is_absolute()
        or relative_path != parsed.as_posix()
        or any(part in {"", ".", ".."} for part in parsed.parts)
        or not parsed.parts
    ):
        _fail("unsafe_relative_path", relative_path)
    directory_descriptor = os.dup(root_descriptor)
    try:
        for part in parsed.parts[:-1]:
            next_descriptor = os.open(
                part,
                os.O_RDONLY
                | getattr(os, "O_DIRECTORY", 0)
                | getattr(os, "O_NOFOLLOW", 0),
                dir_fd=directory_descriptor,
            )
            os.close(directory_descriptor)
            directory_descriptor = next_descriptor
        descriptor = os.open(
            parsed.parts[-1],
            os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0),
            dir_fd=directory_descriptor,
        )
        try:
            return _read_descriptor_bytes(descriptor, relative_path)
        finally:
            os.close(descriptor)
    except FileNotFoundError:
        _fail("missing_input", relative_path)
    except OSError as error:
        _fail("unsafe_input_read", f"{relative_path}: {error.errno}")
    finally:
        os.close(directory_descriptor)


