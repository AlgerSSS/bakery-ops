def _audit_by_table(model: dict[str, object]) -> dict[str, dict[str, object]]:
    audits = model.get("minimum_grain_audits")
    if type(audits) is not list:
        _fail("invalid_resolved_model", "minimum_grain_audits")
    result = {
        str(row["table_name"]): row
        for row in audits
        if type(row) is dict and type(row.get("table_name")) is str
    }
    if len(result) != len(audits):
        _fail("invalid_resolved_model", "minimum grain audit identity")
    return result


def _all_foreign_key_labels(
    model: dict[str, object],
) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    outgoing: dict[str, list[str]] = {}
    incoming: dict[str, list[str]] = {}
    tables = model["tables"]
    assert type(tables) is list
    for table in tables:
        assert type(table) is dict
        table_name = str(table["name"])
        outgoing.setdefault(table_name, [])
        incoming.setdefault(table_name, [])
        for field in table["fields"]:
            if field["fk"]:
                target = str(field["fk"])
                ref_table = target.split(".", maxsplit=1)[0]
                label = (
                    f"{field['name']} -> {target} [{field['fk_activation']}]"
                )
                outgoing[table_name].append(label)
                incoming.setdefault(ref_table, []).append(
                    f"{table_name}.{field['name']} [{field['fk_activation']}]"
                )
        for foreign_key in table["foreign_keys"]:
            columns = ",".join(foreign_key["columns"])
            ref_columns = ",".join(foreign_key["ref_columns"])
            target = f"{foreign_key['ref_table']}({ref_columns})"
            label = f"({columns}) -> {target} [{foreign_key['fk_activation']}]"
            outgoing[table_name].append(label)
            incoming.setdefault(str(foreign_key["ref_table"]), []).append(
                f"{table_name}({columns}) [{foreign_key['fk_activation']}]"
            )
    return (
        {key: sorted(value) for key, value in outgoing.items()},
        {key: sorted(value) for key, value in incoming.items()},
    )


def _table_constraint_text(table: dict[str, object]) -> dict[str, str]:
    field_checks = [
        f"{field['name']}: {check}"
        for field in table["fields"]
        for check in field["checks"]
    ]
    return {
        "checks": _joined(list(table["checks"]) + field_checks),
        "exclusions": _joined(table["exclusions"]),
        "nulls_distinct": _joined(
            [" + ".join(row) for row in table["nulls_distinct_uniques"]]
        ),
        "nulls_not_distinct": _joined(
            [" + ".join(row) for row in table["nulls_not_distinct_uniques"]]
        ),
        "uniques": _joined([" + ".join(row) for row in table["uniques"]]),
    }


