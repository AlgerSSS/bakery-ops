def _reject_float(_: str) -> NoReturn:
    _fail("non_integer_number", "overlay numbers must be exact integers")


def _reject_constant(value: str) -> NoReturn:
    _fail("invalid_json_constant", value)


def _closed_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            _fail("duplicate_json_key", key)
        if key in DANGEROUS_KEYS:
            _fail("dangerous_json_key", key)
        result[key] = value
    return result


def _parse_json_bytes(content: bytes) -> dict[str, object]:
    if type(content) is not bytes:
        _fail("bytes_required", "JSON entrypoint accepts exact bytes only")
    if not content or len(content) > MAX_OVERLAY_BYTES:
        _fail("invalid_overlay_size", str(len(content)))
    if content.startswith(b"\xef\xbb\xbf"):
        _fail("bom_forbidden", "UTF-8 BOM is not allowed")
    try:
        text = content.decode("utf-8", errors="strict")
    except UnicodeDecodeError as error:
        _fail("invalid_utf8", str(error))
    try:
        value = json.loads(
            text,
            object_pairs_hook=_closed_object,
            parse_float=_reject_float,
            parse_constant=_reject_constant,
        )
    except OverlayContractError:
        raise
    except json.JSONDecodeError as error:
        _fail("invalid_json", f"line {error.lineno} column {error.colno}")
    if type(value) is not dict:
        _fail("object_required", "overlay root must be an object")
    return value


def _parse_canonical_json_payload(
    content: bytes, context: str
) -> dict[str, object]:
    if type(content) is not bytes:
        _fail("bytes_required", context)
    if not content or len(content) > MAX_PAYLOAD_BYTES:
        _fail("invalid_payload_size", f"{context}: {len(content)}")
    if content.startswith(b"\xef\xbb\xbf"):
        _fail("bom_forbidden", context)
    try:
        text = content.decode("utf-8", errors="strict")
        value = json.loads(
            text,
            object_pairs_hook=_closed_object,
            parse_float=_reject_float,
            parse_constant=_reject_constant,
        )
    except OverlayContractError:
        raise
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        _fail("invalid_json_payload", f"{context}: {error}")
    if type(value) is not dict:
        _fail("object_required", context)
    if content != _canonical_source_bytes(value):
        _fail("non_canonical_json_payload", context)
    return value


def _canonical_source_bytes(value: object) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    ).encode("utf-8")


def _canonical_contract_bytes(value: object) -> bytes:
    return json.dumps(
        value, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")


def _media_type(path: str) -> str:
    if path.endswith(".json"):
        return "application/json"
    if path.endswith(".csv"):
        return "text/csv; charset=utf-8"
    if path.endswith(".md"):
        return "text/markdown; charset=utf-8"
    if path.endswith(".drawio"):
        return "application/vnd.jgraph.mxfile"
    if path.endswith(".sha256"):
        return "text/plain; charset=us-ascii"
    _fail("unknown_media_type", path)


def _validate_relative_path(path: object, context: str) -> str:
    checked = _require_string(path, context)
    parsed = PurePosixPath(checked)
    if (
        parsed.is_absolute()
        or checked != parsed.as_posix()
        or any(part in {"", ".", ".."} for part in parsed.parts)
        or "\\" in checked
    ):
        _fail("unsafe_relative_path", checked)
    return checked


def _validate_sha256(value: object, context: str) -> str:
    checked = _require_string(value, context)
    if len(checked) != 64 or any(character not in "0123456789abcdef" for character in checked):
        _fail("invalid_sha256", context)
    return checked


def seal_payloads(
    payloads: dict[str, bytes], inputs: list[dict[str, object]]
) -> dict[str, bytes]:
    """Return a closed deterministic bundle with detached hashes and no hash cycle."""

    if type(payloads) is not dict:
        _fail("exact_dict_required", "payloads")
    if frozenset(payloads) != frozenset(PAYLOAD_NAMES):
        _fail(
            "payload_set_mismatch",
            f"missing={sorted(set(PAYLOAD_NAMES) - set(payloads))}; "
            f"unknown={sorted(set(payloads) - set(PAYLOAD_NAMES))}",
        )
    checked_payloads: dict[str, bytes] = {}
    for name in PAYLOAD_NAMES:
        content = payloads[name]
        if type(content) is not bytes:
            _fail("bytes_required", f"payload {name}")
        if not content or len(content) > MAX_PAYLOAD_BYTES:
            _fail("invalid_payload_size", f"{name}: {len(content)}")
        checked_payloads[name] = content

    if type(inputs) is not list:
        _fail("exact_list_required", "inputs")
    checked_inputs: list[dict[str, object]] = []
    seen_inputs: set[str] = set()
    input_keys = frozenset({"path", "sha256", "size_bytes"})
    for index, entry in enumerate(inputs):
        checked = _require_exact_keys(entry, input_keys, f"inputs[{index}]")
        path = _validate_relative_path(checked["path"], f"inputs[{index}].path")
        if path in seen_inputs:
            _fail("duplicate_input_path", path)
        seen_inputs.add(path)
        checked_inputs.append(
            {
                "path": path,
                "sha256": _validate_sha256(
                    checked["sha256"], f"inputs[{index}].sha256"
                ),
                "size_bytes": _require_integer(
                    checked["size_bytes"], f"inputs[{index}].size_bytes"
                ),
            }
        )
    checked_inputs.sort(key=lambda entry: str(entry["path"]))

    bundle = dict(checked_payloads)
    for name in PAYLOAD_NAMES:
        digest = _sha256(checked_payloads[name])
        bundle[f"{name}.sha256"] = f"{digest}  {name}\n".encode("ascii")

    output_rows = [
        {
            "media_type": _media_type(name),
            "path": name,
            "sha256": _sha256(content),
            "size_bytes": len(content),
        }
        for name, content in sorted(bundle.items())
    ]
    manifest = {
        "apply_compatibility": "NOT_APPLY_COMPATIBLE",
        "diagram_status": "GENERATED_FROM_RESOLVED_MODEL",
        "hash_semantics": (
            "outputs exclude manifest.json and manifest.json.sha256; the detached "
            "manifest seal closes the acyclic bundle"
        ),
        "input_snapshot_semantics": (
            "ONE_O_NOFOLLOW_DIRFD_BYTE_SNAPSHOT_USED_FOR_VERIFY_RENDER_HASH_AND_"
            "PUBLISH_NO_LATER_DISK_READ"
        ),
        "execution_source_binding": (
            "BYTE_CARRYING_COMPILE_EXEC_BOOTSTRAP_COMPILER_BYTES_ARE_ATTESTED_"
            "SNAPSHOT;BOOTSTRAP_TRUST_ROOT_REQUIRES_"
            "SERIALIZED_WORKTREE_FROM_LAUNCH"
        ),
        "inputs": checked_inputs,
        "manifest_version": 1,
        "outputs": output_rows,
        "production_data_gate": "BLOCKED",
        "release_status": "DESIGN_ONLY_NOT_COMPILED",
        "revision_id": "R6A1-FX-SIGNED-POS",
    }
    manifest_bytes = _canonical_source_bytes(manifest)
    bundle["manifest.json"] = manifest_bytes
    bundle["manifest.json.sha256"] = (
        f"{_sha256(manifest_bytes)}  manifest.json\n".encode("ascii")
    )
    return {name: bundle[name] for name in sorted(bundle)}


def _require_exact_keys(
    value: object, expected: frozenset[str], context: str
) -> dict[str, object]:
    if type(value) is not dict:
        _fail("invalid_shape", f"{context} must be an object")
    actual = frozenset(value)
    if actual != expected:
        missing = sorted(expected - actual)
        unknown = sorted(actual - expected)
        _fail(
            "closed_schema_violation",
            f"{context}: missing={missing}; unknown={unknown}",
        )
    return value


def _require_list(value: object, context: str) -> list[object]:
    if type(value) is not list:
        _fail("invalid_shape", f"{context} must be an array")
    return value


def _require_string(value: object, context: str) -> str:
    if type(value) is not str or not value:
        _fail("invalid_scalar", f"{context} must be a non-empty string")
    return value


def _require_integer(value: object, context: str) -> int:
    if type(value) is not int or value < 0:
        _fail("invalid_scalar", f"{context} must be a non-negative exact integer")
    return value


def _require_string_list(value: object, context: str) -> list[str]:
    items = _require_list(value, context)
    checked = [_require_string(item, f"{context}[]") for item in items]
    if len(checked) != len(set(checked)):
        _fail("duplicate_array_value", context)
    return checked


def derive_affected_table_contract_names() -> dict[str, tuple[str, ...]]:
    """Derive the closed Phase1 and future table sets from approved paths."""

    phase1_paths = (
        PHASE1_CURRENCY_DEFAULT_PATHS
        + PHASE1_CURRENCY_FIELD_REMOVALS
        + PHASE1_CURRENCY_FK_ONLY_PATHS
        + PHASE1_NON_CURRENCY_FIELD_REMOVALS
        + tuple(path for path, _ in PHASE1_NON_CURRENCY_DEFAULT_REMOVALS)
        + PHASE1_PARENT_REFERENCE_UNIQUE_ADDITIONS
    )
    phase1_path_targets = {
        path.rsplit(".", 1)[0]
        for path in phase1_paths
    }
    phase1 = phase1_path_targets | set(PHASE1_DIRECT_CHANGED_TABLES)
    future = {path.rsplit(".", 1)[0] for path in FUTURE_CURRENCY_DEFAULT_PATHS}
    return {
        "future": tuple(sorted(future)),
        "phase1": tuple(sorted(phase1)),
    }


def _validate_contract_collection(
    value: object,
    *,
    context: str,
    identities: dict[str, tuple[str, str | None, str | None]],
) -> list[dict[str, object]]:
    contracts = _require_list(value, context)
    names: list[str] = []
    checked_contracts: list[dict[str, object]] = []
    for index, contract in enumerate(contracts):
        item = _require_exact_keys(
            contract, SCHEMA_CONTRACT_KEYS, f"{context}[{index}]"
        )
        name = _require_string(item["object_name"], f"{context}[{index}].object_name")
        names.append(name)
        _require_string(
            item["exact_schema_status"], f"{context}[{index}].exact_schema_status"
        )
        _require_string(item["operation"], f"{context}[{index}].operation")
        if item["requested_field_count"] is not None:
            requested_count = _require_integer(
                item["requested_field_count"],
                f"{context}[{index}].requested_field_count",
            )
            if requested_count < 1:
                _fail("invalid_scalar", f"{context}[{index}].requested_field_count")
        if item["contract"] is not None and type(item["contract"]) is not dict:
            _fail("invalid_shape", f"{context}[{index}].contract must be an object")
        baseline_name = item["baseline_object_name"]
        baseline_digest = item["baseline_table_canonical_sha256"]
        if baseline_name is None or baseline_digest is None:
            if baseline_name is not None or baseline_digest is not None:
                _fail(
                    "invalid_shape",
                    f"{context}[{index}] baseline name/hash must be paired",
                )
        else:
            _require_string(baseline_name, f"{context}[{index}].baseline_object_name")
            _validate_sha256(
                baseline_digest,
                f"{context}[{index}].baseline_table_canonical_sha256",
            )
        checked_contracts.append(item)
    if len(names) != len(set(names)):
        _fail("duplicate_schema_contract", f"{context}.object_name must be unique")
    if frozenset(names) != frozenset(identities):
        _fail(
            "schema_contract_identity_mismatch",
            f"{context}: missing={sorted(set(identities) - set(names))}; "
            f"unknown={sorted(set(names) - set(identities))}",
        )
    for item in checked_contracts:
        expected = identities[str(item["object_name"])]
        actual = (
            item["operation"],
            item["baseline_object_name"],
            item["baseline_table_canonical_sha256"],
        )
        if actual != expected:
            _fail(
                "schema_contract_identity_mismatch",
                f"{context}.{item['object_name']}: {actual!r}",
            )
    return checked_contracts


def _validate_exact_view_contract(value: object) -> dict[str, object]:
    contract = _require_exact_keys(
        value, VIEW_EXACT_CONTRACT_KEYS, "view_contract_scope.contract"
    )
    expected_counts = {
        "affected_baseline_field_count": 281,
        "affected_resolved_field_count": 365,
        "baseline_declared_view_count": 59,
        "baseline_view_field_count": 643,
        "resolved_declared_view_count": 59,
        "resolved_view_field_count": 727,
    }
    for key, expected in expected_counts.items():
        if _require_integer(contract[key], f"view_contract_scope.contract.{key}") != expected:
            _fail("view_contract_count_mismatch", key)

    nnd_value = _require_exact_keys(
        contract["grain_nulls_not_distinct_columns"],
        frozenset(VIEW_GRAIN_NULLS_NOT_DISTINCT_COLUMNS),
        "view_contract_scope.contract.grain_nulls_not_distinct_columns",
    )
    nnd_columns: dict[str, tuple[str, ...]] = {}
    for view_name, expected_columns in VIEW_GRAIN_NULLS_NOT_DISTINCT_COLUMNS.items():
        actual_columns = tuple(
            _require_string_list(
                nnd_value[view_name],
                "view_contract_scope.contract.grain_nulls_not_distinct_columns."
                f"{view_name}",
            )
        )
        if actual_columns != expected_columns:
            _fail("view_contract_grain_mismatch", view_name)
        nnd_columns[view_name] = actual_columns

    rename_rows = _require_list(
        contract["renames"], "view_contract_scope.contract.renames"
    )
    renames: dict[str, str] = {}
    for index, row in enumerate(rename_rows):
        checked = _require_exact_keys(
            row, VIEW_RENAME_KEYS, f"view_contract_scope.contract.renames[{index}]"
        )
        source = _require_string(
            checked["from"], f"view_contract_scope.contract.renames[{index}].from"
        )
        target = _require_string(
            checked["to"], f"view_contract_scope.contract.renames[{index}].to"
        )
        if source in renames:
            _fail("duplicate_view_rename", source)
        renames[source] = target
    if renames != VIEW_RENAMES:
        _fail("view_rename_mismatch", repr(renames))

    rows = _require_list(contract["views"], "view_contract_scope.contract.views")
    baseline_names: list[str] = []
    resolved_names: list[str] = []
    baseline_field_total = 0
    resolved_field_total = 0
    forbidden_field_names = {
        "component_cost_myr",
        "normalized_price_myr",
        "price_myr_per_base_unit",
    }
    for index, row in enumerate(rows):
        checked = _require_exact_keys(
            row, VIEW_EXACT_ENTRY_KEYS, f"view_contract_scope.contract.views[{index}]"
        )
        context = f"view_contract_scope.contract.views[{index}]"
        baseline_name = _require_string(checked["baseline_name"], f"{context}.baseline_name")
        resolved_name = _require_string(checked["name"], f"{context}.name")
        baseline_names.append(baseline_name)
        resolved_names.append(resolved_name)
        _validate_sha256(
            checked["baseline_view_canonical_sha256"],
            f"{context}.baseline_view_canonical_sha256",
        )
        baseline_count = _require_integer(
            checked["baseline_field_count"], f"{context}.baseline_field_count"
        )
        resolved_count = _require_integer(
            checked["resolved_field_count"], f"{context}.resolved_field_count"
        )
        if baseline_count < 1 or resolved_count < 1:
            _fail("view_contract_count_mismatch", resolved_name)
        baseline_field_total += baseline_count
        resolved_field_total += resolved_count

        expected_name = VIEW_RENAMES.get(baseline_name, baseline_name)
        expected_operation = (
            "RENAME_AND_REPLACE_VIEW"
            if baseline_name in VIEW_RENAMES
            else "REPLACE_VIEW"
        )
        if resolved_name != expected_name or checked["operation"] != expected_operation:
            _fail("view_contract_identity_mismatch", baseline_name)

        field_rows = _require_list(checked["fields"], f"{context}.fields")
        field_names: list[str] = []
        field_nullable: dict[str, bool] = {}
        for field_index, field in enumerate(field_rows):
            field_context = f"{context}.fields[{field_index}]"
            checked_field = _require_exact_keys(
                field, VIEW_FIELD_SPEC_KEYS, field_context
            )
            field_name = _require_string(checked_field["name"], f"{field_context}.name")
            _require_string(checked_field["data_type"], f"{field_context}.data_type")
            if type(checked_field["nullable"]) is not bool:
                _fail("invalid_scalar", f"{field_context}.nullable")
            field_names.append(field_name)
            field_nullable[field_name] = checked_field["nullable"]
        if len(field_names) != resolved_count or len(field_names) != len(set(field_names)):
            _fail("view_contract_field_mismatch", resolved_name)
        if forbidden_field_names & set(field_names):
            _fail("legacy_myr_view_field_present", resolved_name)

        grain_value = checked["grain_key"]
        if grain_value is None:
            grain: list[str] | None = None
        else:
            grain = _require_string_list(grain_value, f"{context}.grain_key")
            if not grain or not set(grain).issubset(field_names):
                _fail("view_contract_grain_mismatch", resolved_name)
        if resolved_name in nnd_columns:
            if grain is None or not set(nnd_columns[resolved_name]).issubset(grain):
                _fail("view_contract_grain_mismatch", resolved_name)
            if not all(field_nullable[column] for column in nnd_columns[resolved_name]):
                _fail("view_contract_grain_mismatch", resolved_name)

        _require_string_list(checked["lineage"], f"{context}.lineage")
        readiness = _require_string(
            checked["readiness_status"], f"{context}.readiness_status"
        )
        readiness_blockers = _require_string_list(
            checked["readiness_blockers"], f"{context}.readiness_blockers"
        )
        if readiness == "PASS_SELECT_SPEC" or not readiness_blockers:
            _fail("view_readiness_auto_promotion", resolved_name)

    if (
        len(baseline_names) != len(set(baseline_names))
        or tuple(sorted(baseline_names)) != VIEW_BASELINE_AFFECTED_NAMES
        or len(resolved_names) != len(set(resolved_names))
        or tuple(sorted(resolved_names)) != VIEW_AFFECTED_NAMES
    ):
        _fail("view_contract_identity_mismatch", "affected set")
    if baseline_field_total != 281 or resolved_field_total != 365:
        _fail("view_contract_count_mismatch", "affected totals")

    by_resolved_name = {
        str(row["name"]): row for row in rows if type(row) is dict
    }
    for view_name in (
        "v_cost_card_material_cost_selection_resolved",
        "v_cost_card_product_cost_component",
    ):
        lineage = by_resolved_name[view_name]["lineage"]
        if type(lineage) is not list or "finance_accounting_entity" in lineage:
            _fail("view_lineage_mismatch", view_name)

    if _sha256(_canonical_contract_bytes(contract)) != VIEW_EXACT_CONTRACT_CANONICAL_SHA256:
        _fail("view_contract_canonical_hash_mismatch", "closed 26-view contract")
    return contract


def _validate_overlay_shape(overlay: dict[str, object]) -> None:
    _require_exact_keys(overlay, TOP_LEVEL_KEYS, "overlay")
    _require_string(overlay["schema_version"], "schema_version")
    _require_string(overlay["revision_id"], "revision_id")
    _require_string(overlay["status"], "status")
    _require_string(overlay["exact_schema_status"], "exact_schema_status")
    expected_identity = {
        "exact_schema_status": "APPROVED_DDL_LEVEL_CONTRACT",
        "revision_id": "R6A1-FX-SIGNED-POS",
        "schema_version": "HOTCRUSH-CORE-V1-R6A1-OVERLAY-CONTRACT-v3",
        "status": "DESIGN_ONLY_EXACT_MODEL_APPROVED_NOT_COMPILED",
    }
    identity_drift = {
        key: overlay[key]
        for key, expected in expected_identity.items()
        if overlay[key] != expected
    }
    if identity_drift:
        _fail("overlay_identity_mismatch", repr(identity_drift))
    if _canonical_contract_bytes(
        overlay["pos_order_item_contract_boundary"]
    ) != _canonical_contract_bytes(POS_ORDER_ITEM_BOUNDARY):
        _fail(
            "pos_order_item_boundary_mismatch",
            repr(overlay["pos_order_item_contract_boundary"]),
        )
    if _canonical_contract_bytes(
        overlay["pos_source_probe_boundary"]
    ) != _canonical_contract_bytes(POS_SOURCE_PROBE_BOUNDARY):
        _fail(
            "pos_source_probe_boundary_mismatch",
            repr(overlay["pos_source_probe_boundary"]),
        )

    changed_paths = _require_exact_keys(
        overlay["approved_changed_paths"], CHANGED_PATH_KEYS, "approved_changed_paths"
    )
    expected_changed_paths = {
        "future_currency_default_removals_and_fk_additions": FUTURE_CURRENCY_DEFAULT_PATHS,
        "phase1_currency_default_removals_and_fk_additions": PHASE1_CURRENCY_DEFAULT_PATHS,
        "phase1_currency_field_removals": PHASE1_CURRENCY_FIELD_REMOVALS,
        "phase1_currency_fk_additions_without_default": PHASE1_CURRENCY_FK_ONLY_PATHS,
        "phase1_non_currency_field_removals": PHASE1_NON_CURRENCY_FIELD_REMOVALS,
        "phase1_non_currency_default_removals": tuple(
            path for path, _ in PHASE1_NON_CURRENCY_DEFAULT_REMOVALS
        ),
        "phase1_parent_reference_unique_additions": (
            PHASE1_PARENT_REFERENCE_UNIQUE_ADDITIONS
        ),
    }
    for key, expected in expected_changed_paths.items():
        actual = _require_string_list(changed_paths[key], f"approved_changed_paths.{key}")
        if tuple(actual) != expected:
            _fail("changed_path_mismatch", key)

    pins = _require_exact_keys(
        overlay["baseline_pins"],
        frozenset({"catalog", "model", "review_package"}),
        "baseline_pins",
    )
    model_pin = _require_exact_keys(
        pins["model"], MODEL_PIN_KEYS, "baseline_pins.model"
    )
    catalog_pin = _require_exact_keys(
        pins["catalog"], MODEL_PIN_KEYS, "baseline_pins.catalog"
    )
    for context, pin in (("model", model_pin), ("catalog", catalog_pin)):
        _require_string(pin["path"], f"baseline_pins.{context}.path")
        _require_string(pin["raw_sha256"], f"baseline_pins.{context}.raw_sha256")
        _require_string(
            pin["canonical_sha256"], f"baseline_pins.{context}.canonical_sha256"
        )
        _require_integer(pin["size_bytes"], f"baseline_pins.{context}.size_bytes")
        _require_integer(
            pin["canonical_size_bytes"],
            f"baseline_pins.{context}.canonical_size_bytes",
        )
    review_pin = _require_exact_keys(
        pins["review_package"], REVIEW_PIN_KEYS, "baseline_pins.review_package"
    )
    _require_string(review_pin["aggregate_scheme"], "review_package.aggregate_scheme")
    _require_string(review_pin["aggregate_sha256"], "review_package.aggregate_sha256")
    _require_integer(review_pin["file_count"], "review_package.file_count")
    review_paths = _require_string_list(review_pin["paths"], "review_package.paths")
    if tuple(review_paths) != REVIEW_PATHS:
        _fail("review_scope_mismatch", "review_package.paths is not the frozen scope")

    decisions = _require_list(overlay["approved_decisions"], "approved_decisions")
    decision_ids: list[str] = []
    for index, decision in enumerate(decisions):
        item = _require_exact_keys(
            decision, DECISION_KEYS, f"approved_decisions[{index}]"
        )
        decision_ids.append(
            _require_string(
                item["decision_id"], f"approved_decisions[{index}].decision_id"
            )
        )
        _require_string(item["status"], f"approved_decisions[{index}].status")
        _require_string(item["summary"], f"approved_decisions[{index}].summary")
        _require_string_list(
            item["unresolved"], f"approved_decisions[{index}].unresolved"
        )
    if len(decision_ids) != len(set(decision_ids)):
        _fail("duplicate_decision_id", "approved_decisions")

    phase1_contracts = _validate_contract_collection(
        overlay["affected_table_contracts"],
        context="affected_table_contracts",
        identities=PHASE1_AFFECTED_TABLE_IDENTITIES,
    )
    future_contracts = _validate_contract_collection(
        overlay["future_affected_table_contracts"],
        context="future_affected_table_contracts",
        identities=FUTURE_AFFECTED_TABLE_IDENTITIES,
    )
    derived = derive_affected_table_contract_names()
    if tuple(sorted(item["object_name"] for item in phase1_contracts)) != derived[
        "phase1"
    ]:
        _fail("affected_table_set_mismatch", "Phase1 paths/direct changes")
    if tuple(sorted(item["object_name"] for item in future_contracts)) != derived[
        "future"
    ]:
        _fail("affected_table_set_mismatch", "future paths")

    mappings = _require_list(overlay["mapping_overrides"], "mapping_overrides")
    for index, mapping in enumerate(mappings):
        item = _require_exact_keys(
            mapping, MAPPING_OVERRIDE_KEYS, f"mapping_overrides[{index}]"
        )
        for key in (
            "authoritative_source",
            "baseline_disposition",
            "baseline_row_canonical_sha256",
            "migration_mode",
            "source_object",
            "status",
            "target_object",
        ):
            _require_string(item[key], f"mapping_overrides[{index}].{key}")
        _validate_sha256(
            item["baseline_row_canonical_sha256"],
            f"mapping_overrides[{index}].baseline_row_canonical_sha256",
        )
        _require_string_list(item["blockers"], f"mapping_overrides[{index}].blockers")
        _require_string_list(
            item["forbidden_transformations"],
            f"mapping_overrides[{index}].forbidden_transformations",
        )

    delivery_gates = _require_exact_keys(
        overlay["delivery_gates"], DELIVERY_GATE_KEYS, "delivery_gates"
    )
    for key in (
        "apply_compatibility",
        "ddl_status",
        "diagram_status",
        "physical_backfill_status",
        "production_data_gate",
    ):
        _require_string(delivery_gates[key], f"delivery_gates.{key}")
    _require_string_list(delivery_gates["blockers"], "delivery_gates.blockers")
    for key in ("database_writes_allowed", "source_reads_allowed"):
        if type(delivery_gates[key]) is not bool:
            _fail("invalid_scalar", f"delivery_gates.{key} must be an exact boolean")
    counts = _require_exact_keys(
        overlay["golden_counts"],
        frozenset(
            {
                "baseline_phase1",
                "minimum_phase1_table_count",
                "superseded_requested_target_phase1",
                "target_blockers",
                "target_status",
            }
        ),
        "golden_counts",
    )
    baseline_counts = _require_exact_keys(
        counts["baseline_phase1"], COUNT_KEYS, "baseline_phase1"
    )
    target_counts = _require_exact_keys(
        counts["superseded_requested_target_phase1"],
        COUNT_KEYS,
        "superseded_requested_target_phase1",
    )
    _require_integer(
        counts["minimum_phase1_table_count"],
        "golden_counts.minimum_phase1_table_count",
    )
    _require_string(counts["target_status"], "golden_counts.target_status")
    _require_string_list(counts["target_blockers"], "golden_counts.target_blockers")
    for context, values in (
        ("baseline_phase1", baseline_counts),
        ("superseded_requested_target_phase1", target_counts),
    ):
        for key in sorted(COUNT_KEYS):
            _require_integer(values[key], f"{context}.{key}")

    view_scope = _require_exact_keys(
        overlay["view_contract_scope"], VIEW_SCOPE_KEYS, "view_contract_scope"
    )
    affected_views = _require_string_list(
        view_scope["affected_views"], "view_contract_scope.affected_views"
    )
    if view_scope["affected_view_set_semantics"] != "CLOSED_EXACT_26":
        _fail("view_scope_mismatch", "affected_view_set_semantics")
    legacy_fields = _require_string_list(
        view_scope["legacy_myr_fields"], "view_contract_scope.legacy_myr_fields"
    )
    known_defects = view_scope["known_contract_defects"]
    if known_defects != VIEW_KNOWN_CONTRACT_DEFECTS:
        _fail("view_scope_mismatch", "known_contract_defects")
    invariants = _require_string_list(
        view_scope["required_invariants"], "view_contract_scope.required_invariants"
    )
    if tuple(affected_views) != VIEW_AFFECTED_NAMES:
        _fail("view_scope_mismatch", "affected_views")
    if tuple(legacy_fields) != VIEW_LEGACY_MYR_FIELDS:
        _fail("view_scope_mismatch", "legacy_myr_fields")
    if tuple(invariants) != VIEW_REQUIRED_INVARIANTS:
        _fail("view_scope_mismatch", "required_invariants")
    _require_integer(
        view_scope["physical_sql_view_count"],
        "view_contract_scope.physical_sql_view_count",
    )
    _require_string(view_scope["status"], "view_contract_scope.status")
    if view_scope["status"] != "APPROVED_EXACT_VIEW_CONTRACTS":
        _fail("view_scope_mismatch", "status")
    _validate_exact_view_contract(view_scope["contract"])


def load_overlay_bytes(content: bytes) -> dict[str, object]:
    """Parse and validate an overlay supplied as exact immutable bytes."""

    overlay = _parse_json_bytes(content)
    if content != _canonical_source_bytes(overlay):
        _fail("non_canonical_overlay", "model-overlay.json bytes are not canonical")
    _validate_overlay_shape(overlay)
    return overlay


def load_overlay() -> dict[str, object]:
    return load_overlay_bytes(_read_regular_file(OVERLAY_PATH))


def _verify_json_pin(pin: dict[str, object]) -> dict[str, object]:
    relative_path = pin["path"]
    if type(relative_path) is not str or relative_path not in {
        "target-model.json",
        "implementation/phase1-catalog-contract.json",
    }:
        _fail("invalid_pin_path", repr(relative_path))
    content = _read_regular_file(CORE_ROOT / relative_path)
    if len(content) != pin["size_bytes"] or _sha256(content) != pin["raw_sha256"]:
        _fail("raw_pin_mismatch", relative_path)
    try:
        parsed = json.loads(content)
    except json.JSONDecodeError as error:
        _fail("invalid_baseline_json", f"{relative_path}: {error}")
    canonical = _canonical_contract_bytes(parsed)
    if (
        len(canonical) != pin["canonical_size_bytes"]
        or _sha256(canonical) != pin["canonical_sha256"]
    ):
        _fail("canonical_pin_mismatch", relative_path)
    return {
        "path": relative_path,
        "size_bytes": len(content),
        "raw_sha256": _sha256(content),
        "canonical_size_bytes": len(canonical),
        "canonical_sha256": _sha256(canonical),
    }


def _verify_review_pin(pin: dict[str, object]) -> dict[str, object]:
    aggregate = hashlib.sha256()
    files: list[dict[str, object]] = []
    for relative_path in REVIEW_PATHS:
        content = _read_regular_file(CORE_ROOT / relative_path)
        digest = _sha256(content)
        aggregate.update(relative_path.encode("utf-8"))
        aggregate.update(b"\0")
        aggregate.update(digest.encode("ascii"))
        aggregate.update(b"\n")
        files.append(
            {"path": relative_path, "size_bytes": len(content), "sha256": digest}
        )
    digest = aggregate.hexdigest()
    if len(files) != pin["file_count"] or digest != pin["aggregate_sha256"]:
        _fail("review_pin_mismatch", f"file_count={len(files)} aggregate={digest}")
    expected_scheme = "sorted relative_path + NUL + file_sha256 + LF"
    if pin["aggregate_scheme"] != expected_scheme:
        _fail("review_scheme_mismatch", repr(pin["aggregate_scheme"]))
    return {
        "aggregate_scheme": expected_scheme,
        "aggregate_sha256": digest,
        "file_count": len(files),
        "files": files,
    }


