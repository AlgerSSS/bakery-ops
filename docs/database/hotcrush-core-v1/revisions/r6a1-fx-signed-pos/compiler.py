def _analyze_resolved_phase1(model: dict[str, object]) -> dict[str, object]:
    tables_value = model.get("tables")
    if type(tables_value) is not list:
        _fail("invalid_resolved_model", "tables")
    core = [
        table
        for table in tables_value
        if type(table) is dict and table.get("lifecycle") == "CORE_MIGRATION"
    ]
    fks: list[dict[str, object]] = []
    subtype_counts = {"ordinary": 0, "nulls_distinct": 0, "nulls_not_distinct": 0}
    for table in core:
        unique_rows = {tuple(row) for row in table["uniques"]}
        nd_rows = {tuple(row) for row in table["nulls_distinct_uniques"]}
        nnd_rows = {tuple(row) for row in table["nulls_not_distinct_uniques"]}
        subtype_counts["nulls_distinct"] += len(nd_rows)
        subtype_counts["nulls_not_distinct"] += len(nnd_rows)
        subtype_counts["ordinary"] += len(unique_rows - nd_rows - nnd_rows)
        for field in table["fields"]:
            if field["fk"] and field["fk_activation"] == "WITH_TABLE":
                ref_table, ref_column = str(field["fk"]).split(".")
                fks.append(
                    {
                        "table": table["name"],
                        "columns": (field["name"],),
                        "ref_table": ref_table,
                        "ref_columns": (ref_column,),
                        "match_type": "SIMPLE",
                        "origin": "FIELD",
                    }
                )
        for foreign_key in table["foreign_keys"]:
            if foreign_key["fk_activation"] == "WITH_TABLE":
                fks.append(
                    {
                        "table": table["name"],
                        "columns": tuple(foreign_key["columns"]),
                        "ref_table": foreign_key["ref_table"],
                        "ref_columns": tuple(foreign_key["ref_columns"]),
                        "match_type": foreign_key["match_type"],
                        "origin": "TABLE",
                    }
                )
    fks.sort(
        key=lambda edge: (
            str(edge["table"]),
            tuple(edge["columns"]),
            str(edge["ref_table"]),
            tuple(edge["ref_columns"]),
            str(edge["origin"]),
        )
    )
    available: dict[str, set[tuple[str, ...]]] = {}
    for table in core:
        pk = tuple(field["name"] for field in table["fields"] if field["pk"])
        available[str(table["name"])] = {
            pk,
            *(tuple(row) for row in table["uniques"]),
        }
    support_indexes: list[dict[str, object]] = []
    for edge in sorted(
        fks,
        key=lambda edge: (
            str(edge["table"]),
            -len(edge["columns"]),
            tuple(edge["columns"]),
            str(edge["ref_table"]),
            tuple(edge["ref_columns"]),
        ),
    ):
        columns = tuple(edge["columns"])
        prefixes = available[str(edge["table"])]
        if any(prefix[: len(columns)] == columns for prefix in prefixes):
            continue
        support_indexes.append({"table": edge["table"], "columns": columns})
        prefixes.add(columns)
    support_indexes.sort(
        key=lambda index: (str(index["table"]), tuple(index["columns"]))
    )
    primary_keys = sum(
        sum(field["pk"] is True for field in table["fields"]) for table in core
    )
    unique_constraints = sum(len(table["uniques"]) for table in core)
    check_constraints = sum(
        len(table["checks"])
        + sum(len(field["checks"]) for field in table["fields"])
        for table in core
    )
    exclusion_constraints = sum(len(table["exclusions"]) for table in core)
    active_foreign_keys = len(fks)
    constraint_comments = (
        primary_keys
        + unique_constraints
        + check_constraints
        + exclusion_constraints
        + active_foreign_keys
    )
    counts = {
        "active_foreign_keys": active_foreign_keys,
        "catalog_total_indexes": (
            primary_keys
            + unique_constraints
            + exclusion_constraints
            + len(support_indexes)
        ),
        "check_constraints": check_constraints,
        "column_comments": sum(len(table["fields"]) for table in core),
        "columns": sum(len(table["fields"]) for table in core),
        "constraint_comments": constraint_comments,
        "exclusion_constraints": exclusion_constraints,
        "foreign_key_support_indexes": len(support_indexes),
        "index_comments": len(support_indexes),
        "primary_keys": primary_keys,
        "sql_views": 0,
        "table_comments": len(core),
        "tables": len(core),
        "unique_constraints": unique_constraints,
    }
    return {
        "active_foreign_keys": fks,
        "core_tables": core,
        "counts": counts,
        "support_indexes": support_indexes,
        "unique_subtypes": subtype_counts,
    }


def validate_resolved_model_contracts(model: dict[str, object]) -> dict[str, int]:
    """Validate exact table identity, types, references, metadata and view closure."""

    if type(model) is not dict or type(model.get("tables")) is not list:
        _fail("invalid_resolved_model", "root/tables")
    tables = model["tables"]
    assert type(tables) is list
    table_map: dict[str, dict[str, object]] = {}
    column_maps: dict[str, dict[str, dict[str, object]]] = {}
    eligible: dict[str, set[tuple[str, ...]]] = {}
    for table in tables:
        if type(table) is not dict:
            _fail("invalid_resolved_model", "table object")
        name = _require_string(table.get("name"), "resolved table name")
        if name in table_map:
            _fail("invalid_resolved_model", f"duplicate table {name}")
        validate_table_contract(table, expected_name=name, expected_field_count=len(table["fields"]))
        for key in ("zh_name", "purpose", "grain", "writer", "source"):
            _require_string(table[key], f"{name}.{key}")
        columns: dict[str, dict[str, object]] = {}
        for field in table["fields"]:
            field_name = str(field["name"])
            if field["pk"] and field["nullable"]:
                _fail("invalid_resolved_model", f"nullable PK {name}.{field_name}")
            for key in ("zh_name", "description", "purpose", "data_type"):
                _require_string(field[key], f"{name}.{field_name}.{key}")
            columns[field_name] = field
        table_map[name] = table
        column_maps[name] = columns
        pk = tuple(field["name"] for field in table["fields"] if field["pk"])
        eligible[name] = {pk, *(tuple(row) for row in table["uniques"])}

    semantic_edges: set[tuple[object, ...]] = set()
    for table_name, table in table_map.items():
        for field in table["fields"]:
            if not field["fk"]:
                continue
            ref_table, ref_column = str(field["fk"]).split(".")
            if ref_table not in table_map or ref_column not in column_maps[ref_table]:
                _fail("invalid_resolved_foreign_key", f"{table_name}.{field['name']}")
            if field["data_type"] != column_maps[ref_table][ref_column]["data_type"]:
                _fail("invalid_resolved_foreign_key", f"type {table_name}.{field['name']}")
            if (ref_column,) not in eligible[ref_table]:
                _fail("invalid_resolved_foreign_key", f"key {ref_table}.{ref_column}")
            if (
                table["lifecycle"] == "CORE_MIGRATION"
                and field["fk_activation"] == "WITH_TABLE"
                and table_map[ref_table]["lifecycle"] != "CORE_MIGRATION"
            ):
                _fail("invalid_resolved_foreign_key", f"active lifecycle {table_name}")
            edge = (table_name, (field["name"],), ref_table, (ref_column,), "SIMPLE")
            if field["fk_activation"] == "WITH_TABLE" and edge in semantic_edges:
                _fail("duplicate_resolved_foreign_key", repr(edge))
            if field["fk_activation"] == "WITH_TABLE":
                semantic_edges.add(edge)
        for foreign_key in table["foreign_keys"]:
            columns = tuple(foreign_key["columns"])
            ref_table = str(foreign_key["ref_table"])
            ref_columns = tuple(foreign_key["ref_columns"])
            if (
                len(columns) < 2
                or len(columns) != len(set(columns))
                or len(ref_columns) != len(set(ref_columns))
                or foreign_key["match_type"] != "SIMPLE"
                or ref_table not in table_map
                or ref_columns not in eligible[ref_table]
            ):
                _fail("invalid_resolved_foreign_key", f"composite {table_name}.{columns}")
            for column, ref_column in zip(columns, ref_columns):
                if (
                    column not in column_maps[table_name]
                    or ref_column not in column_maps[ref_table]
                    or column_maps[table_name][column]["data_type"]
                    != column_maps[ref_table][ref_column]["data_type"]
                ):
                    _fail("invalid_resolved_foreign_key", f"type {table_name}.{columns}")
            if (
                table["lifecycle"] == "CORE_MIGRATION"
                and foreign_key["fk_activation"] == "WITH_TABLE"
                and table_map[ref_table]["lifecycle"] != "CORE_MIGRATION"
            ):
                _fail("invalid_resolved_foreign_key", f"active lifecycle {table_name}")
            edge = (
                table_name,
                columns,
                ref_table,
                ref_columns,
                foreign_key["match_type"],
            )
            if foreign_key["fk_activation"] == "WITH_TABLE" and edge in semantic_edges:
                _fail("duplicate_resolved_foreign_key", repr(edge))
            if foreign_key["fk_activation"] == "WITH_TABLE":
                semantic_edges.add(edge)

    views = model.get("views")
    if type(views) is not list or len(views) != 59:
        _fail("invalid_resolved_model", "view count")
    if sum(len(view["fields"]) for view in views) != 727:
        _fail("invalid_resolved_model", "view field count")
    computed_bases = _compute_view_base_tables(views, tables)
    if model.get("view_base_tables") != computed_bases:
        _fail("invalid_resolved_model", "view_base_tables")
    if len(model.get("minimum_grain_audits", [])) != len(tables):
        _fail("invalid_resolved_model", "minimum_grain_audits coverage")
    global_counts = {
        "physical_fields": sum(len(table["fields"]) for table in tables),
        "physical_tables": len(tables),
        "total_declared_fields": sum(len(table["fields"]) for table in tables)
        + sum(len(view["fields"]) for view in views),
        "view_fields": sum(len(view["fields"]) for view in views),
        "views": len(views),
    }
    if global_counts != EXPECTED_RESOLVED_GLOBAL_COUNTS:
        _fail("resolved_global_count_mismatch", repr(global_counts))
    return global_counts


