class OverlayContractError(ValueError):
    """A deterministic, machine-readable overlay contract failure."""

    def __init__(self, code: str, detail: str) -> None:
        super().__init__(f"{code}: {detail}")
        self.code = code
        self.detail = detail


def _fail(code: str, detail: str) -> NoReturn:
    raise OverlayContractError(code, detail)


def _sha256(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _read_descriptor_bytes(descriptor: int, context: str) -> bytes:
    before = os.fstat(descriptor)
    if not stat.S_ISREG(before.st_mode):
        _fail("non_regular_input", context)
    chunks: list[bytes] = []
    total = 0
    while True:
        chunk = os.read(descriptor, 1024 * 1024)
        if not chunk:
            break
        chunks.append(chunk)
        total += len(chunk)
        if total > MAX_PAYLOAD_BYTES:
            _fail("input_too_large", context)
    content = b"".join(chunks)
    after = os.fstat(descriptor)
    before_identity = (
        before.st_dev,
        before.st_ino,
        before.st_size,
        before.st_mtime_ns,
        before.st_ctime_ns,
    )
    after_identity = (
        after.st_dev,
        after.st_ino,
        after.st_size,
        after.st_mtime_ns,
        after.st_ctime_ns,
    )
    if before_identity != after_identity or len(content) != before.st_size:
        _fail("input_changed_during_read", context)
    return content


def _read_regular_file_uncached(path: Path) -> bytes:
    descriptor: int | None = None
    context = (
        path.relative_to(CORE_ROOT).as_posix()
        if path.is_relative_to(CORE_ROOT)
        else str(path)
    )
    try:
        descriptor = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    except FileNotFoundError:
        _fail("missing_input", context)
    except OSError as error:
        _fail("unsafe_input_read", f"{context}: {error.errno}")
    assert descriptor is not None
    try:
        return _read_descriptor_bytes(descriptor, context)
    finally:
        os.close(descriptor)


