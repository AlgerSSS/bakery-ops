    root_descriptor = os.open(
        CORE_ROOT,
        os.O_RDONLY
        | getattr(os, "O_DIRECTORY", 0)
        | getattr(os, "O_NOFOLLOW", 0),
    )
    revision_relative = _revision_relative_path()
    overlay_relative = f"{revision_relative}/model-overlay.json"
    compiler_relative = f"{revision_relative}/compiler.py"
    snapshot: dict[str, bytes] = {}
    try:
        for relative_path in _input_relative_paths():
            if relative_path == compiler_relative:
                content = _STARTUP_COMPILER_SOURCE_BYTES
            elif relative_path == overlay_relative and overlay_bytes is not None:
                if type(overlay_bytes) is not bytes:
                    _fail("bytes_required", "overlay_bytes")
                content = overlay_bytes
            else:
                content = _read_relative_regular_file(
                    root_descriptor, relative_path
                )
            snapshot[relative_path] = content
    finally:
        os.close(root_descriptor)
    return MappingProxyType(snapshot)


