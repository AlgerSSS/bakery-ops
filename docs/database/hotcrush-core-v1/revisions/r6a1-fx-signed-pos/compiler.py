def _create_publish_temporary(parent_descriptor: int) -> tuple[str, int, tuple[int, int]]:
    for _ in range(256):
        name = f".r6a1-publish-{os.urandom(16).hex()}"
        try:
            os.mkdir(name, 0o700, dir_fd=parent_descriptor)
        except FileExistsError:
            continue
        try:
            descriptor = os.open(
                name,
                os.O_RDONLY
                | getattr(os, "O_DIRECTORY", 0)
                | getattr(os, "O_NOFOLLOW", 0),
                dir_fd=parent_descriptor,
            )
        except OSError as error:
            _fail("unsafe_publish_temporary", f"{name}: {error.errno}")
        identity = _directory_identity(os.fstat(descriptor))
        return name, descriptor, identity
    _fail("publish_temporary_exhausted", "256 candidate names already exist")


def _verify_named_directory_identity(
    parent_descriptor: int,
    name: str,
    expected_identity: tuple[int, int],
    *,
    error_code: str,
) -> None:
    try:
        metadata = os.stat(name, dir_fd=parent_descriptor, follow_symlinks=False)
    except OSError as error:
        _fail(error_code, f"{name}: {error.errno}")
    if (
        not stat.S_ISDIR(metadata.st_mode)
        or _directory_identity(metadata) != expected_identity
    ):
        _fail(error_code, name)


def _verify_open_directory_bundle(
    bundle: Mapping[str, bytes],
    directory_descriptor: int,
    expected_identity: tuple[int, int],
    *,
    error_code: str,
) -> None:
    before = os.fstat(directory_descriptor)
    if (
        not stat.S_ISDIR(before.st_mode)
        or _directory_identity(before) != expected_identity
    ):
        _fail(error_code, "open directory identity drifted")
    try:
        names = sorted(os.listdir(directory_descriptor))
        actual = {
            name: _read_regular_file_at(directory_descriptor, name)
            for name in names
        }
    except OverlayContractError:
        _fail(error_code, "open directory payload is unsafe")
    after = os.fstat(directory_descriptor)
    if (
        _directory_identity(after) != expected_identity
        or actual != dict(bundle)
    ):
        _fail(error_code, "open directory payload differs")


def _open_named_directory(
    parent_descriptor: int, name: str, *, error_code: str
) -> tuple[int, tuple[int, int]]:
    try:
        before = os.stat(name, dir_fd=parent_descriptor, follow_symlinks=False)
    except OSError as error:
        _fail(error_code, f"{name}: {error.errno}")
    if not stat.S_ISDIR(before.st_mode):
        _fail(error_code, name)
    try:
        descriptor = os.open(
            name,
            os.O_RDONLY
            | getattr(os, "O_DIRECTORY", 0)
            | getattr(os, "O_NOFOLLOW", 0),
            dir_fd=parent_descriptor,
        )
    except OSError as error:
        _fail(error_code, f"{name}: {error.errno}")
    identity = _directory_identity(os.fstat(descriptor))
    if identity != _directory_identity(before):
        os.close(descriptor)
        _fail(error_code, name)
    for child in sorted(os.listdir(descriptor)):
        metadata = os.stat(child, dir_fd=descriptor, follow_symlinks=False)
        if not stat.S_ISREG(metadata.st_mode):
            os.close(descriptor)
            _fail(error_code, child)
    return descriptor, identity


def _write_publish_file(
    directory_descriptor: int, name: str, content: bytes
) -> None:
    _validate_publish_name(name, "publish payload")
    try:
        descriptor = os.open(
            name,
            os.O_WRONLY
            | os.O_CREAT
            | os.O_EXCL
            | getattr(os, "O_NOFOLLOW", 0),
            0o600,
            dir_fd=directory_descriptor,
        )
    except FileExistsError:
        _fail("publish_temporary_collision", name)
    try:
        view = memoryview(content)
        written = 0
        while written < len(view):
            count = os.write(descriptor, view[written:])
            if count <= 0:
                _fail("publish_write_failed", name)
            written += count
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def _cleanup_publish_temporary(
    parent_descriptor: int,
    temporary_name: str,
    expected_identity: tuple[int, int],
) -> None:
    try:
        descriptor = os.open(
            temporary_name,
            os.O_RDONLY
            | getattr(os, "O_DIRECTORY", 0)
            | getattr(os, "O_NOFOLLOW", 0),
            dir_fd=parent_descriptor,
        )
    except FileNotFoundError:
        _fail("publish_temporary_identity_drift", temporary_name)
    except OSError as error:
        _fail("publish_temporary_identity_drift", f"{temporary_name}: {error.errno}")
    try:
        if _directory_identity(os.fstat(descriptor)) != expected_identity:
            _fail("publish_temporary_identity_drift", temporary_name)
        names = os.listdir(descriptor)
        unexpected = sorted(set(names) - set(PAYLOAD_NAMES) - {
            f"{name}.sha256" for name in PAYLOAD_NAMES
        } - {"manifest.json", "manifest.json.sha256"})
        if unexpected:
            _fail("publish_temporary_identity_drift", repr(unexpected))
        for name in sorted(names):
            metadata = os.stat(name, dir_fd=descriptor, follow_symlinks=False)
            if not stat.S_ISREG(metadata.st_mode):
                _fail("publish_temporary_identity_drift", name)
            os.unlink(name, dir_fd=descriptor)
        os.fsync(descriptor)
    finally:
        os.close(descriptor)
    current = os.stat(
        temporary_name,
        dir_fd=parent_descriptor,
        follow_symlinks=False,
    )
    if (
        not stat.S_ISDIR(current.st_mode)
        or _directory_identity(current) != expected_identity
    ):
        _fail("publish_temporary_identity_drift", temporary_name)
    # Under the repository's serialized/cooperative-writer boundary, the final
    # identity-check-to-rmdir interval is safe and failed publishes leave no
    # tombstone. This does not claim protection from a hostile same-UID writer.
    try:
        os.rmdir(temporary_name, dir_fd=parent_descriptor)
    except OSError as error:
        _fail("publish_temporary_cleanup_failed", f"{temporary_name}: {error.errno}")


def publish_package(
    bundle: dict[str, bytes], destination: Path | None = None
) -> str:
    """Atomically install or replace a closed bundle, with rollback on failure."""

    if _ACTIVE_INPUT_SNAPSHOT.get() is None:
        snapshot = _capture_input_snapshot(None)
        token = _ACTIVE_INPUT_SNAPSHOT.set(snapshot)
        try:
            return publish_package(bundle, destination)
        finally:
            _ACTIVE_INPUT_SNAPSHOT.reset(token)

    _validate_sealed_bundle(bundle)
    target = REVISION_ROOT / "generated" if destination is None else Path(destination)
    parent = target.parent
    target_name = _validate_publish_name(target.name, "publish target")
    parent_descriptor = _open_directory_no_follow(parent)
    parent_identity = _directory_identity(os.fstat(parent_descriptor))
    temporary_name: str | None = None
    temporary_descriptor: int | None = None
    temporary_identity: tuple[int, int] | None = None
    try:
        _verify_directory_path_identity(parent, parent_identity)
        replace_existing = False
        try:
            existing = _compare_published_bundle_at(
                bundle, parent_descriptor, target_name
            )
        except OverlayContractError as error:
            if error.code != "publish_destination_drift":
                raise
            existing = "DRIFT"
            replace_existing = True
        if existing == "NOOP":
            _verify_directory_path_identity(parent, parent_identity)
            return existing
        (
            temporary_name,
            temporary_descriptor,
            temporary_identity,
        ) = _create_publish_temporary(parent_descriptor)
        for name in sorted(bundle):
            _write_publish_file(temporary_descriptor, name, bundle[name])
        os.fsync(temporary_descriptor)
        _verify_named_directory_identity(
            parent_descriptor,
            temporary_name,
            temporary_identity,
            error_code="publish_temporary_identity_drift",
        )
        _verify_open_directory_bundle(
            bundle,
            temporary_descriptor,
            temporary_identity,
            error_code="publish_temporary_content_drift",
        )
        _verify_directory_path_identity(parent, parent_identity)
        if not replace_existing:
            try:
                _atomic_rename_no_replace(
                    parent_descriptor, temporary_name, target_name
                )
            except FileExistsError:
                if (
                    _compare_published_bundle_at(
                        bundle, parent_descriptor, target_name
                    )
                    != "NOOP"
                ):
                    _fail("publish_race_target_missing", str(target))
                _verify_directory_path_identity(parent, parent_identity)
                return "NOOP"
            temporary_name = None
            _verify_named_directory_identity(
                parent_descriptor,
                target_name,
                temporary_identity,
                error_code="publish_destination_identity_drift",
            )
            if (
                _compare_published_bundle_at(
                    bundle, parent_descriptor, target_name
                )
                != "NOOP"
            ):
                _fail("publish_destination_drift", str(target))
        else:
            old_descriptor, old_identity = _open_named_directory(
                parent_descriptor,
                target_name,
                error_code="unsafe_publish_destination",
            )
            exchanged = False
            try:
                _verify_named_directory_identity(
                    parent_descriptor,
                    temporary_name,
                    temporary_identity,
                    error_code="publish_temporary_identity_drift",
                )
                _verify_open_directory_bundle(
                    bundle,
                    temporary_descriptor,
                    temporary_identity,
                    error_code="publish_temporary_content_drift",
                )
                _verify_named_directory_identity(
                    parent_descriptor,
                    target_name,
                    old_identity,
                    error_code="publish_destination_identity_drift",
                )
                _atomic_exchange(
                    parent_descriptor, temporary_name, target_name
                )
                exchanged = True
                try:
                    _verify_named_directory_identity(
                        parent_descriptor,
                        target_name,
                        temporary_identity,
                        error_code="publish_destination_identity_drift",
                    )
                    _verify_named_directory_identity(
                        parent_descriptor,
                        temporary_name,
                        old_identity,
                        error_code="publish_recovery_identity_drift",
                    )
                    _verify_open_directory_bundle(
                        bundle,
                        temporary_descriptor,
                        temporary_identity,
                        error_code="publish_destination_drift",
                    )
                    if (
                        _compare_published_bundle_at(
                            bundle, parent_descriptor, target_name
                        )
                        != "NOOP"
                    ):
                        _fail("publish_destination_drift", str(target))
                except BaseException as publication_error:
                    try:
                        _verify_named_directory_identity(
                            parent_descriptor,
                            temporary_name,
                            old_identity,
                            error_code="publish_rollback_identity_drift",
                        )
                        _atomic_exchange(
                            parent_descriptor, temporary_name, target_name
                        )
                        exchanged = False
                        _verify_named_directory_identity(
                            parent_descriptor,
                            target_name,
                            old_identity,
                            error_code="publish_rollback_failed",
                        )
                        _verify_named_directory_identity(
                            parent_descriptor,
                            temporary_name,
                            temporary_identity,
                            error_code="publish_rollback_failed",
                        )
                    except BaseException as rollback_error:
                        _fail(
                            "publish_rollback_failed",
                            f"publish={publication_error}; rollback={rollback_error}",
                        )
                    raise
                temporary_identity = old_identity
            finally:
                os.close(old_descriptor)
                if exchanged:
                    # The old bundle remains at the private temporary name until
                    # all new target bytes and identities have been reverified.
                    pass
        os.close(temporary_descriptor)
        temporary_descriptor = None
        os.fsync(parent_descriptor)
        _verify_directory_path_identity(parent, parent_identity)
        return "PUBLISHED"
    finally:
        if temporary_descriptor is not None:
            os.close(temporary_descriptor)
        if temporary_name is not None and temporary_identity is not None:
            _cleanup_publish_temporary(
                parent_descriptor, temporary_name, temporary_identity
            )
        os.close(parent_descriptor)


def build_package(overlay_bytes: bytes | None = None) -> dict[str, bytes]:
    """Build the complete package in memory or fail before any filesystem write."""

    if _ACTIVE_INPUT_SNAPSHOT.get() is None:
        snapshot = _capture_input_snapshot(overlay_bytes)
        token = _ACTIVE_INPUT_SNAPSHOT.set(snapshot)
        try:
            return build_package(overlay_bytes)
        finally:
            _ACTIVE_INPUT_SNAPSHOT.reset(token)

    overlay = load_overlay() if overlay_bytes is None else load_overlay_bytes(overlay_bytes)
    verify_baseline_pins(overlay)
    verify_schema_contract_baselines(overlay)
    verify_view_contract_baselines(overlay)
    verify_currency_changed_path_baseline(overlay)
    _validate_count_boundaries(overlay)
    _validate_raw_replay_boundary(overlay)
    verify_raw_replay_mapping_baseline(overlay)
    _validate_release_boundary(overlay)
    _validate_group_reporting_boundary(overlay)
    _validate_recipe_archive_boundary(overlay)
    _require_approved_exact_schema(overlay)
    _require_recipe_archive_resolution(overlay)
    _require_approved_view_contracts(overlay)
    gates = overlay["delivery_gates"]
    assert type(gates) is dict
    if gates["diagram_status"] != "GENERATED_FROM_RESOLVED_MODEL":
        _fail(
            "missing_resolved_diagram",
            "the revision relationship diagram must be generated from the resolved model",
        )
    resolved = build_resolved_model(overlay)
    validate_resolved_model_contracts(resolved)
    analysis = _analyze_resolved_phase1(resolved)
    counts = analysis["counts"]
    if counts != EXPECTED_RESOLVED_PHASE1_COUNTS:
        _fail("resolved_phase1_count_mismatch", repr(counts))
    expected_subtypes = {
        "ordinary": 87,
        "nulls_distinct": 16,
        "nulls_not_distinct": 10,
    }
    if analysis["unique_subtypes"] != expected_subtypes:
        _fail("resolved_unique_subtype_mismatch", repr(analysis["unique_subtypes"]))
    source_bytes = (
        _read_regular_file(OVERLAY_PATH) if overlay_bytes is None else overlay_bytes
    )
    payloads = _render_payloads(source_bytes, overlay, resolved, analysis)
    inputs = build_input_manifest(overlay, source_bytes)
    bundle = seal_payloads(payloads, inputs)
    _validate_sealed_bundle(bundle, verify_provenance=False)
    final_inputs = build_input_manifest(overlay, source_bytes)
    if final_inputs != inputs:
        _fail("input_changed_during_build", "input manifest drift after sealing")
    return bundle


def build_and_publish(
    destination: Path | None = None,
) -> tuple[dict[str, bytes], str]:
    """Build, validate and atomically publish under one immutable input snapshot."""

    if _ACTIVE_INPUT_SNAPSHOT.get() is None:
        snapshot = _capture_input_snapshot(None)
        token = _ACTIVE_INPUT_SNAPSHOT.set(snapshot)
        try:
            bundle = build_package()
            return bundle, publish_package(bundle, destination)
        finally:
            _ACTIVE_INPUT_SNAPSHOT.reset(token)
    bundle = build_package()
    return bundle, publish_package(bundle, destination)


def main(argv: list[str] | None = None) -> int:
    arguments = sys.argv[1:] if argv is None else argv
    if arguments not in (["check"], ["generate"]):
        print("usage: compiler.py {check|generate}", file=sys.stderr)
        return 64
    try:
        if arguments == ["generate"]:
            bundle, status = build_and_publish()
        else:
            bundle = build_package()
            status = "CHECKED"
    except OverlayContractError as error:
        print(str(error), file=sys.stderr)
        return 2
    print(
        f"{status}: manifest_sha256={_sha256(bundle['manifest.json'])}; "
        f"files={len(bundle)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
