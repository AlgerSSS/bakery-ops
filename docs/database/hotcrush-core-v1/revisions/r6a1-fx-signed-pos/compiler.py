def _field_key_text(table: dict[str, object], field: dict[str, object]) -> str:
    labels: list[str] = []
    name = str(field["name"])
    if field["pk"]:
        labels.append("PK")
    for unique in table["uniques"]:
        if name in unique:
            labels.append(f"UQ({','.join(unique)})")
    if field["fk"]:
        labels.append(f"FK->{field['fk']}")
    labels.extend(str(check) for check in field["checks"])
    return " | ".join(labels)


