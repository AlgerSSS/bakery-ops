def build_input_manifest(
    overlay: dict[str, object] | None = None,
    overlay_bytes: bytes | None = None,
) -> list[dict[str, object]]:
    """Hash every file whose bytes or executable logic influence the package."""

    checked = load_overlay() if overlay is None else overlay
    if overlay_bytes is not None:
        if type(overlay_bytes) is not bytes:
            _fail("bytes_required", "overlay_bytes")
        supplied = load_overlay_bytes(overlay_bytes)
        if (
            _canonical_contract_bytes(supplied)
            != _canonical_contract_bytes(checked)
            or overlay_bytes != _canonical_source_bytes(checked)
        ):
            _fail("overlay_bytes_mismatch", "parsed overlay differs from build input")
    verify_baseline_pins(checked)
    revision_relative = REVISION_ROOT.relative_to(CORE_ROOT).as_posix()
    overlay_relative = f"{revision_relative}/model-overlay.json"
    rows: list[dict[str, object]] = []
    for relative_path in _input_relative_paths():
        content = (
            overlay_bytes
            if overlay_bytes is not None and relative_path == overlay_relative
            else _read_regular_file(CORE_ROOT / relative_path)
        )
        assert type(content) is bytes
        rows.append(
            {
                "path": relative_path,
                "sha256": _sha256(content),
                "size_bytes": len(content),
            }
        )
    return rows


