def _merge_resolved_views(
    model: dict[str, object], overlay: dict[str, object]
) -> list[dict[str, object]]:
    baseline_views = model.get("views")
    if type(baseline_views) is not list:
        _fail("invalid_baseline_model", "views array is missing")
    baseline_by_name = {
        str(view["name"]): view
        for view in baseline_views
        if type(view) is dict and type(view.get("name")) is str
    }
    if len(baseline_by_name) != len(baseline_views):
        _fail("invalid_baseline_model", "view identities are invalid")
    scope = overlay["view_contract_scope"]
    assert type(scope) is dict and type(scope["contract"]) is dict
    exact_views = scope["contract"]["views"]
    assert type(exact_views) is list
    replacements: dict[str, dict[str, object]] = {}
    for exact in exact_views:
        assert type(exact) is dict
        baseline_name = str(exact["baseline_name"])
        source = baseline_by_name.get(baseline_name)
        if source is None:
            _fail("view_contract_identity_mismatch", baseline_name)
        baseline_fields = {
            str(field["name"]): field
            for field in source["fields"]
            if type(field) is dict and type(field.get("name")) is str
        }
        resolved = copy.deepcopy(source)
        resolved["name"] = exact["name"]
        if exact["name"] != baseline_name:
            resolved["zh_name"] = f"R6A1结构视图：{exact['name']}"
        resolved["fields"] = [
            _structural_view_field(spec, baseline_fields.get(str(spec["name"])))
            for spec in exact["fields"]
            if type(spec) is dict
        ]
        resolved["lineage"] = copy.deepcopy(exact["lineage"])
        resolved["grain_key"] = copy.deepcopy(exact["grain_key"])
        resolved["grain"] = (
            "R6A1 structure-only; grain key unresolved"
            if exact["grain_key"] is None
            else " × ".join(str(item) for item in exact["grain_key"])
        )
        resolved["readiness_status"] = exact["readiness_status"]
        resolved["readiness_blockers"] = copy.deepcopy(
            exact["readiness_blockers"]
        )
        resolved["notes"] = (
            "R6A1 closed structural field/type/nullability/lineage contract. "
            "New field business metadata is explicitly STRUCTURAL_CONTRACT_ONLY; "
            "readiness is not promoted and SELECT specification remains blocked."
        )
        replacements[baseline_name] = resolved
    merged = [
        replacements.get(str(view["name"]), copy.deepcopy(view))
        for view in baseline_views
        if type(view) is dict
    ]
    return sorted(merged, key=lambda view: str(view["name"]))


def _compute_view_base_tables(
    views: list[dict[str, object]], tables: list[dict[str, object]]
) -> dict[str, list[str]]:
    view_by_name = {str(view["name"]): view for view in views}
    table_names = {str(table["name"]) for table in tables}
    memo: dict[str, tuple[str, ...]] = {}

    def visit(name: str, stack: tuple[str, ...]) -> tuple[str, ...]:
        if name in memo:
            return memo[name]
        if name in stack:
            _fail("view_lineage_cycle", " -> ".join(stack + (name,)))
        view = view_by_name.get(name)
        if view is None:
            _fail("unknown_view_lineage", name)
        lineage = view.get("lineage")
        if type(lineage) is not list:
            _fail("invalid_resolved_model", f"{name}.lineage")
        base: set[str] = set()
        for dependency in lineage:
            if type(dependency) is not str:
                _fail("invalid_resolved_model", f"{name}.lineage scalar")
            if dependency in table_names:
                base.add(dependency)
            elif dependency in view_by_name:
                base.update(visit(dependency, stack + (name,)))
            else:
                _fail("unknown_view_lineage", f"{name}: {dependency}")
        memo[name] = tuple(sorted(base))
        return memo[name]

    return {name: list(visit(name, ())) for name in sorted(view_by_name)}


