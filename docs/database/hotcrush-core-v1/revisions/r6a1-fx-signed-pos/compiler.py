def _validate_publish_name(name: str, context: str) -> str:
    if not name or name in {".", ".."} or "/" in name or "\0" in name:
        _fail("unsafe_publish_name", context)
    return name


def _open_directory_no_follow(path: Path) -> int:
    flags = (
        os.O_RDONLY
        | getattr(os, "O_DIRECTORY", 0)
        | getattr(os, "O_NOFOLLOW", 0)
        | getattr(os, "O_CLOEXEC", 0)
    )
    components = path.parts
    if path.is_absolute():
        descriptor = os.open(os.sep, flags)
        components = components[1:]
    else:
        descriptor = os.open(".", flags)
    try:
        for component in components:
            if component in {"", ".", ".."}:
                _fail("unsafe_publish_parent", str(path))
            next_descriptor = os.open(component, flags, dir_fd=descriptor)
            os.close(descriptor)
            descriptor = next_descriptor
        return descriptor
    except FileNotFoundError:
        os.close(descriptor)
        _fail("missing_publish_parent", str(path))
    except OSError as error:
        os.close(descriptor)
        _fail("unsafe_publish_parent", f"{path}: {error.errno}")
    except BaseException:
        os.close(descriptor)
        raise


def _directory_identity(metadata: os.stat_result) -> tuple[int, int]:
    return metadata.st_dev, metadata.st_ino


def _verify_directory_path_identity(
    path: Path, expected_identity: tuple[int, int]
) -> None:
    try:
        metadata = path.lstat()
    except FileNotFoundError:
        _fail("publish_parent_identity_drift", str(path))
    if (
        not stat.S_ISDIR(metadata.st_mode)
        or path.is_symlink()
        or _directory_identity(metadata) != expected_identity
    ):
        _fail("publish_parent_identity_drift", str(path))


def _read_regular_file_at(directory_descriptor: int, name: str) -> bytes:
    _validate_publish_name(name, name)
    try:
        descriptor = os.open(
            name,
            os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0),
            dir_fd=directory_descriptor,
        )
    except OSError as error:
        _fail("publish_destination_drift", f"{name}: {error.errno}")
    try:
        return _read_descriptor_bytes(descriptor, name)
    finally:
        os.close(descriptor)


def _compare_published_bundle_at(
    bundle: dict[str, bytes], parent_descriptor: int, target_name: str
) -> str:
    _validate_publish_name(target_name, "publish target")
    try:
        metadata = os.stat(
            target_name, dir_fd=parent_descriptor, follow_symlinks=False
        )
    except FileNotFoundError:
        return "MISSING"
    if not stat.S_ISDIR(metadata.st_mode):
        _fail("unsafe_publish_destination", target_name)
    try:
        target_descriptor = os.open(
            target_name,
            os.O_RDONLY
            | getattr(os, "O_DIRECTORY", 0)
            | getattr(os, "O_NOFOLLOW", 0),
            dir_fd=parent_descriptor,
        )
    except OSError as error:
        _fail("unsafe_publish_destination", f"{target_name}: {error.errno}")
    try:
        target_identity = _directory_identity(os.fstat(target_descriptor))
        if target_identity != _directory_identity(metadata):
            _fail("publish_destination_identity_drift", target_name)
        names = os.listdir(target_descriptor)
        if len(names) != len(set(names)):
            _fail("publish_destination_drift", target_name)
        actual = {
            name: _read_regular_file_at(target_descriptor, name)
            for name in sorted(names)
        }
        try:
            current = os.stat(
                target_name, dir_fd=parent_descriptor, follow_symlinks=False
            )
        except FileNotFoundError:
            _fail("publish_destination_identity_drift", target_name)
        if (
            not stat.S_ISDIR(current.st_mode)
            or _directory_identity(current) != target_identity
        ):
            _fail("publish_destination_identity_drift", target_name)
    finally:
        os.close(target_descriptor)
    if actual != bundle:
        _fail("publish_destination_drift", target_name)
    return "NOOP"


def _compare_published_bundle(
    bundle: dict[str, bytes], destination: Path
) -> str:
    target = Path(destination)
    parent = target.parent
    target_name = _validate_publish_name(target.name, "publish target")
    parent_descriptor = _open_directory_no_follow(parent)
    try:
        return _compare_published_bundle_at(
            bundle, parent_descriptor, target_name
        )
    finally:
        os.close(parent_descriptor)


def _atomic_rename_no_replace(
    parent_descriptor: int, source_name: str, target_name: str
) -> None:
    source = _validate_publish_name(source_name, "publish temporary")
    target = _validate_publish_name(target_name, "publish target")
    library = ctypes.CDLL(None, use_errno=True)
    if sys.platform == "darwin":
        function = getattr(library, "renameatx_np", None)
        flag = 0x00000004  # RENAME_EXCL from macOS sys/stdio.h.
    elif sys.platform.startswith("linux"):
        function = getattr(library, "renameat2", None)
        flag = 0x00000001  # RENAME_NOREPLACE from Linux uapi/linux/fs.h.
    else:
        function = None
        flag = 0
    if function is None:
        _fail("atomic_no_replace_unsupported", sys.platform)
    function.argtypes = [
        ctypes.c_int,
        ctypes.c_char_p,
        ctypes.c_int,
        ctypes.c_char_p,
        ctypes.c_uint,
    ]
    function.restype = ctypes.c_int
    ctypes.set_errno(0)
    result = function(
        parent_descriptor,
        os.fsencode(source),
        parent_descriptor,
        os.fsencode(target),
        flag,
    )
    if result == 0:
        return
    error_number = ctypes.get_errno()
    if error_number in {errno.EEXIST, errno.ENOTEMPTY}:
        raise FileExistsError(
            error_number, os.strerror(error_number), target_name
        )
    if error_number in {
        getattr(errno, "ENOSYS", 78),
        getattr(errno, "ENOTSUP", 45),
    }:
        _fail("atomic_no_replace_unsupported", f"{sys.platform}: {error_number}")
    _fail("atomic_publish_rename_failed", f"{target_name}: {error_number}")


