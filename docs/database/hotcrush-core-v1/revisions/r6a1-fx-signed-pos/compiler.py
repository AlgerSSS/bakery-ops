def verify_currency_changed_path_baseline(
    overlay: dict[str, object] | None = None,
) -> dict[str, int]:
    """Verify the expected-before state for every approved currency path."""

    checked = load_overlay() if overlay is None else overlay
    model = _load_pinned_baseline_model(checked)
    table_by_name: dict[str, dict[str, object]] = {}
    for table in model["tables"]:
        if type(table) is not dict or type(table.get("name")) is not str:
            _fail("invalid_baseline_model", "table name is invalid")
        name = table["name"]
        if name in table_by_name:
            _fail("invalid_baseline_model", f"duplicate table {name}")
        table_by_name[name] = table

    def find(path: str) -> tuple[dict[str, object], dict[str, object]]:
        table_name, field_name = path.split(".", maxsplit=1)
        table = table_by_name.get(table_name)
        if table is None or type(table.get("fields")) is not list:
            _fail("currency_before_state_mismatch", f"missing table {table_name}")
        matches = [
            field
            for field in table["fields"]
            if type(field) is dict and field.get("name") == field_name
        ]
        if len(matches) != 1:
            _fail("currency_before_state_mismatch", f"field {path} count={len(matches)}")
        return table, matches[0]

    def verify_default_path(path: str, expected_core: bool) -> None:
        before_path = PHASE1_CURRENCY_BASELINE_PATHS.get(path, path)
        table, field = find(before_path)
        is_core = table.get("lifecycle") == "CORE_MIGRATION"
        if is_core != expected_core:
            _fail("currency_before_state_mismatch", f"lifecycle {path}")
        if (
            field.get("default") != "'MYR'"
            or field.get("fk") is not None
            or field.get("fk_activation") != "WITH_TABLE"
        ):
            _fail("currency_before_state_mismatch", f"default/FK {path}")

    for path in PHASE1_CURRENCY_DEFAULT_PATHS:
        verify_default_path(path, expected_core=True)
    for path in PHASE1_CURRENCY_FIELD_REMOVALS:
        verify_default_path(path, expected_core=True)
    for path in FUTURE_CURRENCY_DEFAULT_PATHS:
        verify_default_path(path, expected_core=False)
    for path in PHASE1_CURRENCY_FK_ONLY_PATHS:
        table, field = find(path)
        if (
            table.get("lifecycle") != "CORE_MIGRATION"
            or field.get("default") is not None
            or field.get("fk") is not None
            or field.get("fk_activation") != "WITH_TABLE"
        ):
            _fail("currency_before_state_mismatch", f"FK-only {path}")
    for path in PHASE1_NON_CURRENCY_FIELD_REMOVALS:
        table, field = find(path)
        if (
            table.get("lifecycle") != "CORE_MIGRATION"
            or field.get("data_type") != "numeric(18,4)"
            or field.get("default") is not None
            or field.get("nullable") is not True
        ):
            _fail("field_removal_before_state_mismatch", path)
    for path, expected_default in PHASE1_NON_CURRENCY_DEFAULT_REMOVALS:
        table, field = find(path)
        if (
            table.get("lifecycle") != "CORE_MIGRATION"
            or field.get("default") != expected_default
            or field.get("nullable") is not False
        ):
            _fail("default_removal_before_state_mismatch", path)
    return {
        "future_defaults_without_fk": len(FUTURE_CURRENCY_DEFAULT_PATHS),
        "phase1_defaults_without_fk": len(PHASE1_CURRENCY_DEFAULT_PATHS),
        "phase1_fields_removed": len(PHASE1_CURRENCY_FIELD_REMOVALS),
        "phase1_no_default_without_fk": len(PHASE1_CURRENCY_FK_ONLY_PATHS),
        "phase1_non_currency_defaults_removed": len(
            PHASE1_NON_CURRENCY_DEFAULT_REMOVALS
        ),
        "phase1_non_currency_fields_removed": len(
            PHASE1_NON_CURRENCY_FIELD_REMOVALS
        ),
    }


def verify_schema_contract_baselines(
    overlay: dict[str, object] | None = None,
) -> dict[str, int]:
    """Pin every replacement table and prove every requested addition is absent."""

    checked = load_overlay() if overlay is None else overlay
    model = _load_pinned_baseline_model(checked)
    table_by_name: dict[str, dict[str, object]] = {}
    for table in model["tables"]:
        if type(table) is not dict or type(table.get("name")) is not str:
            _fail("invalid_baseline_model", "table name is invalid")
        name = table["name"]
        if name in table_by_name:
            _fail("invalid_baseline_model", f"duplicate table {name}")
        table_by_name[name] = table

    counts = {
        "future_existing_tables_pinned": 0,
        "phase1_additions_absent": 0,
        "phase1_existing_tables_pinned": 0,
    }
    collections = (
        ("phase1", checked["affected_table_contracts"]),
        ("future", checked["future_affected_table_contracts"]),
    )
    for collection_name, contracts in collections:
        assert type(contracts) is list
        for contract in contracts:
            assert type(contract) is dict
            target_name = str(contract["object_name"])
            baseline_name = contract["baseline_object_name"]
            expected_digest = contract["baseline_table_canonical_sha256"]
            if baseline_name is None:
                if (
                    collection_name != "phase1"
                    or contract["operation"] != "ADD_TABLE"
                    or target_name in table_by_name
                ):
                    _fail("baseline_table_absence_mismatch", target_name)
                counts["phase1_additions_absent"] += 1
                continue
            assert type(baseline_name) is str
            assert type(expected_digest) is str
            table = table_by_name.get(baseline_name)
            if table is None:
                _fail("missing_baseline_table", baseline_name)
            actual_digest = _sha256(_canonical_contract_bytes(table))
            if actual_digest != expected_digest:
                _fail("baseline_table_pin_mismatch", baseline_name)
            if contract["operation"] == "RENAME_AND_REPLACE_TABLE":
                if target_name == baseline_name or target_name in table_by_name:
                    _fail("baseline_rename_target_collision", target_name)
            elif contract["operation"] == "REPLACE_TABLE":
                if target_name != baseline_name:
                    _fail("baseline_replace_name_mismatch", target_name)
            else:
                _fail("invalid_schema_operation", str(contract["operation"]))
            counts[f"{collection_name}_existing_tables_pinned"] += 1
    return counts


def verify_view_contract_baselines(
    overlay: dict[str, object] | None = None,
) -> dict[str, int]:
    """Pin all 26 affected baseline views and independently recompute deltas."""

    checked = load_overlay() if overlay is None else overlay
    model = _load_pinned_baseline_model(checked)
    views = model["views"]
    if type(views) is not list:
        _fail("invalid_baseline_model", "views")
    view_by_name: dict[str, dict[str, object]] = {}
    baseline_field_count = 0
    for view in views:
        if type(view) is not dict or type(view.get("name")) is not str:
            _fail("invalid_baseline_model", "view name")
        name = view["name"]
        if name in view_by_name or type(view.get("fields")) is not list:
            _fail("invalid_baseline_model", f"duplicate/invalid view {name}")
        view_by_name[name] = view
        baseline_field_count += len(view["fields"])
    if len(view_by_name) != 59 or baseline_field_count != 643:
        _fail("baseline_view_count_mismatch", f"{len(view_by_name)}/{baseline_field_count}")

    scope = checked["view_contract_scope"]
    assert type(scope) is dict and type(scope["contract"]) is dict
    contract = scope["contract"]
    contract_rows = contract["views"]
    assert type(contract_rows) is list
    affected_baseline_fields = 0
    affected_resolved_fields = 0
    for row in contract_rows:
        assert type(row) is dict
        baseline_name = str(row["baseline_name"])
        baseline_view = view_by_name.get(baseline_name)
        if baseline_view is None:
            _fail("missing_baseline_view", baseline_name)
        actual_digest = _sha256(_canonical_contract_bytes(baseline_view))
        if actual_digest != row["baseline_view_canonical_sha256"]:
            _fail("baseline_view_pin_mismatch", baseline_name)
        actual_field_count = len(baseline_view["fields"])
        if actual_field_count != row["baseline_field_count"]:
            _fail("baseline_view_field_count_mismatch", baseline_name)
        affected_baseline_fields += actual_field_count
        fields = row["fields"]
        assert type(fields) is list
        affected_resolved_fields += len(fields)

    resolved_field_count = (
        baseline_field_count - affected_baseline_fields + affected_resolved_fields
    )
    result = {
        "affected_baseline_fields": affected_baseline_fields,
        "affected_resolved_fields": affected_resolved_fields,
        "baseline_fields": baseline_field_count,
        "baseline_views": len(view_by_name),
        "resolved_fields": resolved_field_count,
        "resolved_views": len(view_by_name),
    }
    if result != {
        "affected_baseline_fields": 281,
        "affected_resolved_fields": 365,
        "baseline_fields": 643,
        "baseline_views": 59,
        "resolved_fields": 727,
        "resolved_views": 59,
    }:
        _fail("view_contract_count_mismatch", repr(result))
    return result


def recompute_baseline_phase1_counts() -> dict[str, int]:
    """Derive baseline counts from catalog rows, never from its declared counts."""

    content = _read_regular_file(
        CORE_ROOT / "implementation/phase1-catalog-contract.json"
    )
    try:
        catalog = json.loads(content)
    except json.JSONDecodeError as error:
        _fail("invalid_baseline_json", f"phase1 catalog: {error}")
    if type(catalog) is not dict:
        _fail("invalid_baseline_catalog", "root must be an object")
    required = {"columns", "constraints", "indexes", "tables"}
    if not required.issubset(catalog):
        _fail("invalid_baseline_catalog", "required row collections are missing")
    tables = catalog["tables"]
    columns = catalog["columns"]
    constraints = catalog["constraints"]
    indexes = catalog["indexes"]
    if not all(type(rows) is list for rows in (tables, columns, constraints, indexes)):
        _fail("invalid_baseline_catalog", "row collections must be arrays")

    by_type = {constraint_type: 0 for constraint_type in ("p", "u", "c", "x", "f")}
    for row in constraints:
        if type(row) is not dict or row.get("type") not in by_type:
            _fail("invalid_baseline_catalog", "unknown constraint row")
        by_type[row["type"]] += 1
    support_indexes = 0
    for row in indexes:
        if type(row) is not dict:
            _fail("invalid_baseline_catalog", "invalid index row")
        if not row.get("is_primary") and not row.get("is_unique") and not row.get(
            "is_exclusion"
        ):
            support_indexes += 1

    def comment_count(rows: list[object], context: str) -> int:
        count = 0
        for row in rows:
            if type(row) is not dict or "comment" not in row:
                _fail("invalid_baseline_catalog", f"{context} comment is missing")
            if type(row["comment"]) is str and row["comment"]:
                count += 1
        return count

    return {
        "active_foreign_keys": by_type["f"],
        "catalog_total_indexes": len(indexes),
        "check_constraints": by_type["c"],
        "column_comments": comment_count(columns, "column"),
        "columns": len(columns),
        "constraint_comments": comment_count(constraints, "constraint"),
        "exclusion_constraints": by_type["x"],
        "foreign_key_support_indexes": support_indexes,
        "index_comments": comment_count(indexes, "index"),
        "primary_keys": by_type["p"],
        "sql_views": 0,
        "table_comments": comment_count(tables, "table"),
        "tables": len(tables),
        "unique_constraints": by_type["u"],
    }


