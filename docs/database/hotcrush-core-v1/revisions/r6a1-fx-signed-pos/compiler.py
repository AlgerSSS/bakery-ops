def _render_csv(
    fieldnames: tuple[str, ...], rows: list[dict[str, object]]
) -> bytes:
    """Render review CSV as deterministic UTF-8 BOM + CRLF bytes."""

    stream = io.StringIO(newline="")
    writer = csv.DictWriter(
        stream,
        fieldnames=fieldnames,
        extrasaction="raise",
        lineterminator="\r\n",
    )
    writer.writeheader()
    for row in rows:
        writer.writerow(
            {
                key: ""
                if row.get(key) is None
                else str(row.get(key))
                for key in fieldnames
            }
        )
    return b"\xef\xbb\xbf" + stream.getvalue().encode("utf-8")


def _read_csv_rows(relative_path: str) -> tuple[tuple[str, ...], list[dict[str, str]]]:
    content = _read_regular_file(CORE_ROOT / relative_path)
    try:
        decoded = content.decode("utf-8-sig", errors="strict")
    except UnicodeDecodeError as error:
        _fail("invalid_baseline_csv", f"{relative_path}: {error}")
    reader = csv.DictReader(io.StringIO(decoded, newline=""))
    if reader.fieldnames is None or len(reader.fieldnames) != len(set(reader.fieldnames)):
        _fail("invalid_baseline_csv", f"{relative_path}: invalid header")
    rows = list(reader)
    if any(None in row for row in rows):
        _fail("invalid_baseline_csv", f"{relative_path}: overflow column")
    return tuple(reader.fieldnames), rows


def _joined(rows: object, separator: str = " | ") -> str:
    if type(rows) is not list and type(rows) is not tuple:
        return ""
    return separator.join(str(item) for item in rows)


