def VF(
    name: str,
    zh: str,
    dtype: str,
    description: str,
    purpose: str,
    *,
    nullable: bool = False,
    sensitive: str = "none",
    example: str = "",
):
    if dtype == "uuid" and example == "...":
        example = str(uuid.uuid5(uuid.NAMESPACE_URL, f"https://hotcrush.example/view-field/{name}"))
    return F(name, zh, dtype, description, purpose, nullable=nullable, sensitive=sensitive, example=example)


def REVIEWED_VIEW(
    name,
    zh_name,
    domain,
    purpose,
    grain,
    readers,
    fields,
    lineage,
    *,
    notes="只读分析接口，不允许作为业务事实写入口。",
):
    """Declare a view using its mandatory, separately reviewed P0b contract."""
    if name not in VIEW_GRAIN_KEYS or name not in VIEW_READINESS_CONTRACTS:
        raise AssertionError(f"view lacks explicit P0b contract: {name}")
    field_tuple = tuple(fields)
    grain_key = VIEW_GRAIN_KEYS[name]
    if grain_key is not None:
        fields_by_name = {field.name: field for field in field_tuple}
        nullable_keys = tuple(
            field_name
            for field_name in grain_key
            if field_name in fields_by_name and fields_by_name[field_name].nullable
        )
        if nullable_keys:
            notes += (
                " 粒度键中的可空字段按 PostgreSQL NULLS NOT DISTINCT / IS NOT DISTINCT FROM 语义分组和去重，"
                f"包括：{', '.join(nullable_keys)}；不得让 NULL 绕过去重或产生重复业务行。"
            )
    readiness_status, readiness_blockers = VIEW_READINESS_CONTRACTS[name]
    return DECLARE_VIEW(
        name,
        zh_name,
        domain,
        purpose,
        grain,
        readers,
        field_tuple,
        lineage,
        readiness_status=readiness_status,
        readiness_blockers=readiness_blockers,
        grain_key=grain_key,
        notes=notes,
    )


